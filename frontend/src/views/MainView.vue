      </div>
      
      <div class="header-center">
        <div class="view-switcher">
          <button 
            v-for="mode in ['graph', 'split', 'workbench']" 
            :key="mode"
            class="switch-btn"
            :class="{ active: viewMode === mode }"
            @click="viewMode = mode"
          >
            {{ { graph: $t('main.layoutGraph'), split: $t('main.layoutSplit'), workbench: $t('main.layoutWorkbench') }[mode] }}
          </button>
        </div>
      </div>

      <div class="header-right">
        <LanguageSwitcher />
        <button class="settings-btn" @click="showSettings = true" :title="$t('settings.title')">
          <span class="gear-icon">⚙</span>
        </button>
        <div class="step-divider"></div>
        <div class="workflow-step">
          <span class="step-num">Step {{ currentStep }}/5</span>
          <span class="step-name">{{ $tm('main.stepNames')[currentStep - 1] }}</span>
        </div>
        <div class="step-divider"></div>
        <span class="status-indicator" :class="statusClass">
          <span class="dot"></span>
          {{ statusText }}
        </span>
      </div>
    </header>

    <!-- Main Content Area -->
    <main class="content-area">
      <!-- Left Panel: Graph -->
      <div class="panel-wrapper left" :style="leftPanelStyle">
        <GraphPanel 
          :graphData="graphData"
          :loading="graphLoading"
          :currentPhase="currentPhase"
          @refresh="refreshGraph"
          @toggle-maximize="toggleMaximize('graph')"
        />
      </div>

      <!-- Right Panel: Step Components -->
      <div class="panel-wrapper right" :style="rightPanelStyle">
        <!-- 本页只负责 Step 1（图谱构建）。
             Step 2 起是独立路由：/simulation/:id（SimulationView 等），
             Step1GraphBuild 完成后直接 router.push 过去。
             这里原先还留着一套 v-if/v-else-if 的 Step 切换接线，但它其实是死路径：
             Step1 从不 emit next-step，currentStep 也就永远停在 1，Step2 那一支从未被渲染；
             而一旦有人把 Step1 改成 emit，走到 currentStep>=3 会得到一个空白面板。
             与其留个陷阱，不如删掉。 -->
        <Step1GraphBuild
          :currentPhase="currentPhase"
          :projectData="projectData"
          :ontologyProgress="ontologyProgress"
          :buildProgress="buildProgress"
          :graphData="graphData"
          :systemLogs="systemLogs"
        />
      </div>
    </main>

    <!-- 已有图谱时重建前必须确认：这一步会删掉旧图谱，还会断开引用它的模拟 -->
    <div v-if="pendingRebuild" class="rebuild-overlay">
      <div class="rebuild-dialog">
        <div class="rebuild-title">{{ $t('step1.rebuildTitle') }}</div>
        <div class="rebuild-body">
          <p>{{ $t('step1.rebuildNodeCount', { count: pendingRebuild.node_count }) }}</p>
          <p v-if="pendingRebuild.referenced_simulations > 0" class="rebuild-warn">
            {{ $t('step1.rebuildRefs', { refs: pendingRebuild.referenced_simulations }) }}
          </p>
        </div>
        <div class="rebuild-actions">
          <button class="rebuild-btn" :disabled="false" @click="cancelRebuild">
            {{ $t('step1.rebuildCancel') }}
